CREATE INDEX IF NOT EXISTS idx_features_diaObjectId ON features (diaObjectId);
CREATE INDEX IF NOT EXISTS idx_features_stem ON features (stem);

CREATE TABLE IF NOT EXISTS model_scores (
    diaSourceId INTEGER NOT NULL REFERENCES features (diaSourceId),
    diaObjectId INTEGER NOT NULL,
    stem TEXT NOT NULL,
    model_role TEXT NOT NULL, -- Champion, Challenger or Retiree
    model_version TEXT NOT NULL,
    extragal REAL,
    mover REAL,
    real REAL,
    bogus REAL,
    agn REAL,
    gal REAL,
    timestamp TEXT NOT NULL DEFAULT current_timestamp,
    UNIQUE (diaSourceId, model_role, model_version) -- Composite key. A row is uniquely identified by a source, model version AND the role of the model*
);

--* So for a given diaSourceId we might have as many as 3 rows, and they are uniquely identified by their source, model version and role. 

CREATE INDEX IF NOT EXISTS idx_model_scores_stem ON model_scores (stem);
